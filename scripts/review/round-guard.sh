#!/usr/bin/env bash
# Round cap for prp-review-agents (prp-framework#151 AC3).
#
# Invariant: R is the number of distinct run ids ([0-9]{8}T[0-9]{6}Z-[0-9a-f]{8}, lower-cased) in
# the input. Every footer the runner posts is byte-exact (the adapter checks
# "Generated-by: prp-review-agents v<ver> run=<id> pass=<name>" before posting). The guard refuses
# (exit 2) when a run= marker is not followed by a readable id, or when a line has generated...by
# (0-20 non-alphanumerics between the words) and names prp-review-agents but carries no id. A
# footer's round can go uncounted without a refusal only if the comment is edited to remove all
# three markers (run=, generated-by, and the tool name) — out of scope, see #213.
# Boundaries, stated:
# - An id split across two lines refuses: the first half follows run= and is not a readable id.
# - A 9-hex id counts as its 8-hex prefix. Two ids differing only in the 9th hex digit count once.
# - run must start a word: workflow_run=, rerun= and prose like "did not run: it" are not markers.
#   Only run= (optional spaces around =) is a marker; run: is not.
# - Fail-closed cost: a run= with an unreadable id refuses, from any bot. A generated-by line
#   refuses only when it also names prp-review-agents; "Report generated by Jenkins." counts 0.
#   Out of scope: a comment edited to lose run=, generated-by and the tool name (prp-framework#213).
#
# usage: round-guard.sh [--cap N] < footer-lines
#   stdin: one line per PR comment = that comment's LAST line (the caller extracts it).
#   exit 0 = allowed (prints "rounds so far: R of N; this is round R+1")
#   exit 3 = refused: cap reached
#   exit 2 = bad argument, unreadable input, an unreadable run id, or grep failure (fail closed)
set -euo pipefail

CAP=10
while [[ $# -gt 0 ]]; do
  case "$1" in
    --cap) [[ $# -ge 2 ]] || { echo "error: --cap needs a value" >&2; exit 2; }; CAP="$2"; shift 2 ;;
    *) echo "error: unknown argument '$1'" >&2; exit 2 ;;
  esac
done
printf '%s' "$CAP" | grep -qxE '[0-9]{1,3}' && [[ "$CAP" =~ ^[0-9]+$ ]] && (( 10#$CAP >= 1 )) \
  || { echo "error: --cap must be a number from 1 to 999" >&2; exit 2; }
CAP=$((10#$CAP))

# A review round is one distinct run id. Every run id token anywhere in the input counts, whatever the rest
# of its line looks like, so no footer shape can hide a round. Ids are compared lower-cased.
ID_RE='[0-9]{8}[Tt][0-9]{6}[Zz]-[0-9A-Fa-f]{8}'
IN=$(cat) || { echo "error: cannot read input — round count unknown, refusing" >&2; exit 2; }
# A footer whose id is unreadable must not vanish: refuse when a run= marker is not followed by an id,
# or when a line that names prp-review-agents in a generated-by attribution (0-20 non-alphanumerics
# between the words) carries no id. "run" must start a word (workflow_run=, rerun= are not markers).
if ! printf '%s\n' "$IN" | LC_ALL=C awk -v id="$ID_RE" '
  { l = tolower($0); t = l
    while (match(t, /(^|[^a-z0-9_])run[[:space:]]*=[[:space:]]*/)) {
      rest = substr(t, RSTART + RLENGTH)
      if (match(rest, "^" tolower(id)) == 0) { bad = 1 }
      t = rest }
    if (l ~ /generated[^a-z0-9]{0,20}by/ && index(l, "prp-review-agents") && l !~ tolower(id)) { bad = 1 } }
  END { exit bad }'; then
  echo "error: a review footer has an unreadable run id — round count unknown, refusing" >&2; exit 2
fi
rc=0
IDS=$(printf '%s\n' "$IN" | LC_ALL=C grep -aoE "$ID_RE") || rc=$?
(( rc <= 1 )) || { echo "error: grep failed (exit $rc) — round count unknown, refusing" >&2; exit 2; }
R=0
[[ -n "$IDS" ]] && R=$(printf '%s\n' "$IDS" | LC_ALL=C tr '[:upper:]' '[:lower:]' | LC_ALL=C sort -u | wc -l | tr -d ' ')

if (( R >= CAP )); then
  echo "ROUND-CAP: refused — this PR already has $R review runs (cap $CAP). Review stop rule: fix open Critical/Important findings or re-route the work; file Medium/Low in ONE follow-up issue; do not start another round; escalate (delegate_or_escalate)." >&2
  exit 3
fi
echo "rounds so far: $R of $CAP; this is round $((R + 1))"
